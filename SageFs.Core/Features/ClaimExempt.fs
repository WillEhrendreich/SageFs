namespace SageFs.Features

open System

/// The pages a script generates, and the one place that says so (P14, finding C6).
///
/// A claim says "I am editing this file, nobody else do". For a page a script writes from other files that is the wrong
/// lock: every landing touches the same generated pages (the roadmap, the configuration tables), so one member's claim
/// held for its whole packet made eight others wait for a file none of them edits by hand. A generated page needs no claim.
/// The landing regenerates it after the rebase, so whatever a member committed for it is replaced by the page the
/// merged tree produces.
///
/// The set is closed: a new generated page is one more case here, and a test fails until every case names its generator.
module ClaimExempt =

  [<RequireQualifiedAccess>]
  type Page =
    | Roadmap
    | Configuration
    | ClientSetup

  let all : Page list = [ Page.Roadmap; Page.Configuration; Page.ClientSetup ]

  /// The repository-relative path of the page.
  let path (page: Page) : string =
    match page with
    | Page.Roadmap -> "docs/roadmap.md"
    | Page.Configuration -> "docs/configuration.md"
    | Page.ClientSetup -> "docs/client-setup.md"

  /// The command that regenerates the page, as a person would type it from the repository root. `<sha>` is the commit the
  /// page's source links point at.
  let command (page: Page) : string =
    match page with
    | Page.Roadmap -> "dotnet fsi scripts/gen-roadmap.fsx"
    | Page.Configuration -> "dotnet fsi scripts/gen-configuration-doc.fsx <sha>"
    | Page.ClientSetup -> "dotnet fsi scripts/gen-client-setup-doc.fsx"

  /// How the landing regenerates the page after the rebase. A page whose script takes no argument is regenerated by the
  /// daemon; one that needs the commit its links name is regenerated against the rebased head.
  [<RequireQualifiedAccess>]
  type Regeneration =
    /// `dotnet fsi <script>` from the worktree root.
    | Script of script: string
    /// `dotnet fsi <script> <rebased head sha>`.
    | ScriptWithCommit of script: string

  let regeneration (page: Page) : Regeneration =
    match page with
    | Page.Roadmap -> Regeneration.Script "scripts/gen-roadmap.fsx"
    | Page.Configuration -> Regeneration.ScriptWithCommit "scripts/gen-configuration-doc.fsx"
    | Page.ClientSetup -> Regeneration.Script "scripts/gen-client-setup-doc.fsx"

  /// The files whose change can change the page. A landing whose diff touches none of them and not the page itself
  /// leaves the page as it was, so nothing is regenerated for it.
  let inputs (page: Page) : string list =
    match page with
    | Page.Roadmap -> [ "scripts/roadmap/"; "scripts/gen-roadmap.fsx"; "docs/plans/" ]
    | Page.Configuration -> [ "SageFs.Core/Timeouts.fs"; "scripts/gen-configuration-doc.fsx" ]
    | Page.ClientSetup -> [ "SageFs.Core/ClientSetup.fs"; "scripts/gen-client-setup-doc.fsx" ]

  let private normalized (raw: string) : string = CohortLandingPlan.normalize raw

  let ofPath (raw: string) : Page option =
    let p = normalized raw
    all |> List.tryFind (fun page -> String.Equals(path page, p, StringComparison.Ordinal))

  let isExemptPath (raw: string) : bool = (ofPath raw).IsSome

  /// The generated page a claim scope names. A project scope never names one.
  let ofScope (scope: SageFs.Cohort.ClaimScope) : Page option =
    match scope with
    | SageFs.Cohort.ClaimScope.File p -> ofPath p
    | SageFs.Cohort.ClaimScope.Project _ -> None

  /// A claim scope that needs no claim.
  let isExempt (scope: SageFs.Cohort.ClaimScope) : bool = (ofScope scope).IsSome

  /// Pages a diff leaves possibly stale: the page itself changed, or one of its inputs did.
  let pagesToRegenerate (changedFiles: string list) : Page list =
    let changed = changedFiles |> List.map normalized
    let touches (page: Page) =
      let own = path page
      changed
      |> List.exists (fun file ->
        file = own
        || inputs page |> List.exists (fun input -> file = input || (input.EndsWith "/" && file.StartsWith(input, StringComparison.Ordinal))))
    all |> List.filter touches

  /// Can a rebase conflict be settled by taking the other side and regenerating? Only when EVERY conflicting file is a
  /// generated page: a conflict in a file somebody wrote is the member's to resolve.
  let conflictIsOnlyGeneratedPages (conflictFiles: string list) : bool =
    match conflictFiles with
    | [] -> false
    | files -> files |> List.forall isExemptPath

  /// What the claim tool answers for a generated page.
  let claimAnswer (page: Page) : string =
    sprintf
      "%s is generated, so it needs no claim and none was taken. Edit the files it is generated from; the landing regenerates it after the rebase. To see it now: %s"
      (path page)
      (command page)
